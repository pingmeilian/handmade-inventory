// ---- 角色分工（V115）----
//
// 用户 2026-10-05：「严格按照我给你的截图来调整配色？手作空间按钮和下面的圆形加号是棕色的」
//
// 设计稿的四色是**分工**：摩卡棕=结构与深色按钮/胶囊、陶土橘=主强调、姜黄=次强调、
// 樱花粉=色带/点睛卡。而项目原先只有"一套 token 通用" ⇒ 橘色到处跑、姜黄完全没上场
// （实测：设计稿姜黄 2479px，真机 12px）。
//
// 做法：给主题加一层**可选的角色映射** roles —— 只声明"这几个位置用哪个 token"，
// **默认值 = 现状**（chip/fab 默认走 primary、highlight 默认走 surface、数字默认全 primary）
// ⇒ 没声明 roles 的主题**逐像素零影响**（判据 ⑮ 逐个钉着）。
// 取值可以是 token 键名，也可以是伪键 'bgSplit'（= 背景拼色那支色，粉帽的加号用它）。
const ROLE_DEFAULTS = {
  // V116：band = 顶部固定区的底色。默认取页面底 ⇒ 没声明这套的主题**外观零变化**；
  //   粉帽声明成 bgSplit（樱花粉）⇒ 固定区是粉、下面仍是奶黄。
  band: 'bg',
  chip: 'primary', chipOn: 'primary-on',
  fab: 'primary', fabOn: 'primary-on',
  // V118：highlightSub = 点睛卡上的**副信息**色。默认 text-2（= 现状 ⇒ 其它主题零影响）；
  //   粉帽声明成 text-1 —— 粉底上 text-2 的对比只有 1.67，看不清。
  highlight: 'surface', highlightOn: 'text-3', highlightSub: 'text-2',
  // V119：ring = 「选中」的荧光描边色。默认 = primary（其它主题颜色不变、只是效果升级）；
  //   粉帽声明成 bgSplit（樱花粉）—— 用户嫌原来的主色实色框像一圈棕方框。
  ring: 'primary',
  num1: 'primary', num2: 'primary', num3: 'primary'
};
const ROLE_KEYS = Object.keys(ROLE_DEFAULTS);

// 把一个角色值解析成色值：token 键 / 伪键 bgSplit / 直接给 #RRGGBB
function roleColor(key, name) {
  const tk = get(key);
  const th = has(key) ? THEMES[key] : THEMES[DEFAULT];
  if (name === 'bgSplit') return (th.bgSplit && th.bgSplit.color) || tk.primary;
  if (/^#[0-9A-Fa-f]{3,8}$/.test(String(name))) return String(name);
  return tk[name] || tk.primary;
}

// 取一套主题的九个角色（缺声明一律回默认 —— 绝不 undefined 进 CSS）

function roles(key) {
  const declared = (has(key) ? THEMES[key].roles : null) || {};
  const out = {};
  ROLE_KEYS.forEach((k) => {
    out[k] = roleColor(key, declared[k] || ROLE_DEFAULTS[k]);
  });
  return out;
}

// 默认主题 = 项目最初那套暖陶土（2026-10-04 用户：「最开始的那个配色作为默认主题」）
// 它同时是 app.json 里导航栏/底栏初始值的那个色 ⇒ 首帧不会先闪一下别的主题。
const DEFAULT = 'clayWarm';

// 主题是否存在（给"存坏了要兜底"的场景用）
function has(key) {
  return !!(key && Object.prototype.hasOwnProperty.call(THEMES, key));
}

// 取一套主题的 token。
// ⚠️ 读不到（未设置 / 值被删 / 存坏）一律回**默认主题** —— 绝不抛异常、绝不白屏。
//    这条是"不需要数据迁移"的前提：老数据里没有 theme 字段，读出来就是默认主题。
function get(key) {
  return (has(key) ? THEMES[key] : THEMES[DEFAULT]).tokens;
}

// 给选择器用：列出全部主题（含画色块要用的几个色 + 中文名）
// `contrast` = 这套是不是"有意的撞色"（见文件头 ⑤）；判据 ⑨ 用它决定走哪个分支。
function list() {
  return Object.keys(THEMES).map((key) => {
    const t = THEMES[key].tokens;
    return {
      key: key, name: THEMES[key].name, contrast: !!THEMES[key].contrast,
      primary: t.primary, soft: t['primary-soft'], accent: t.accent
    };
  });
}

// 主题名（找不到回默认的名字）
function nameOf(key) {
  return (has(key) ? THEMES[key] : THEMES[DEFAULT]).name;
}

// 输出给 page-meta 的 page-style 用的 CSS 变量串。
// 13 个变量一次全给 —— 少一个就会出现"主色换了、阴影还是旧的"这种"90% 换了"的脏感。
function styleOf(key) {
  const t = get(key);
  let s = Object.keys(t).map((k) => '--color-' + k + ': ' + t[k] + ';').join(' ');
  // 背景拼色（V114 起 = 主题可选属性 bgSplit.color，樱花粉那支色）
  // ⚠️ V116 口径变更：它**不再**由页面背景渐变承担（原做法：「屏高 16% 以上铺粉」，见已删代码），
  //   改成**顶部固定带的底色** —— .pin-band 走 --color-band 角色（bgSplit 是伪键，见 roleColor）。
  //   为什么改：用户 2026-10-05「固定住的部分背景是粉色，再往下就是奶黄色」⇒ 粉的范围
  //   应当跟着**固定区高度**走，而不是一个固定屏高比例（四页固定区高矮本来就不同）。
  // 角色分工（V115）：无论主题有没有声明，九个角色变量**一律发**——
  // 缺声明就是默认值（= primary / surface…），这样使用端只有一套写法。
  const rl = roles(key);
  const NAME = { band: 'band', chip: 'chip', chipOn: 'chip-on', fab: 'fab', fabOn: 'fab-on',
    highlight: 'highlight', highlightOn: 'highlight-on', highlightSub: 'highlight-sub',
    ring: 'ring',
    num1: 'num-1', num2: 'num-2', num3: 'num-3' };
  ROLE_KEYS.forEach((k) => { s += ' --color-' + NAME[k] + ': ' + rl[k] + ';'; });
  // ---- 可选的「带内前景」（V154）----
  // 为什么单独一组、且**默认不发**：本项目的带色一直是**浅色**（粉 / 浅绿 / 浅黄），
  //   带上的文字直接用 text-* 就够。但「苹果爱丽丝·红带」是第一套**深色带** ——
  //   带内那几处按「浅带」配的元素（带上深字、主色实心块）压上去只有 1.00（看不见），
  //   而那是**功能可见性**问题（「批量入库」入口会消失）。
  //   ⇒ 声明式：主题想用就写 bandInk / bandInkOn；**没写的一律不发这个变量**，
  //     wxss 里的 `var(--color-band-ink, <原值>)` fallback 生效 ⇒ 既有主题零影响。
  const th2 = has(key) ? THEMES[key] : THEMES[DEFAULT];
  if (th2.bandInk) s += ' --color-band-ink: ' + roleColor(key, th2.bandInk) + ';';
  if (th2.bandInkOn) s += ' --color-band-ink-on: ' + roleColor(key, th2.bandInkOn) + ';';
  return s;
}

module.exports = { DEFAULT, THEMES, has, get, list, nameOf, styleOf, roles };
