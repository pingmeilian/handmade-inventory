// utils/themes.js —— 主题的唯一真相源（V97 · 按手作空间换色）
//
// 为什么单独一个文件：
//   主题色以前只写在 app.wxss 的 page 选择器里（全局唯一，没有"几套"的概念）。
//   现在要"按手作空间换"，就必须有个地方能回答两件事：
//     ① 一共有哪几套主题、每套叫什么
//     ② 每套的 13 个 token 具体是什么值
//   这里只放**数据 + 纯函数**（不碰 storage、不碰页面），所以能被单测直接盯住。
//
// 📌 2026-10-04 主题表定在 4 套；**2026-10-13（V151）加第 5 套「青提可露丽·绿带」**（用户发来新色板）；
//    **2026-10-14 第 6 套「苹果爱丽丝·红带」**（V153 加；**V154 按用户点名的落点重配** ——
//    他说"我要顶部是红色 背景是黄色，加号是蓝色"，于是色带换成深红、底色换成浅黄）：
//    · **暖陶土**  —— 项目**最初**那套配色（V96 及以前一直硬编码在 app.wxss 里）。
//                    用户说「主题还是之前的棕色，最开始的那个」并要求**它当默认主题**
//                    ⇒ 从散落的硬编码收成一套正式主题，并设为 DEFAULT。
//                    收成主题有个额外好处：app.json 里那些打包期定死的初始值
//                    （导航栏底 #FAF6F0 / 底栏选中 #C28E72 / 底栏底 #FFFDFA）
//                    **正好就是这套色** —— 首帧不再"先闪一下别的主题"。
//    · 海盐奶盖 / 铁皮饼干盒 —— 用户发设计稿加的两套（其余 9 套甜品色板已删）。
//    声明了 `contrast: true`（撞色）：海盐奶盖 / 铁皮饼干盒 / **苹果爱丽丝·红带**；
//    **常规**主题：暖陶土 / 姜饼粉帽 / 青提可露丽·绿带。
//    带 `bgSplit`（顶部背景拼色）的：姜饼粉帽 / 青提可露丽·绿带 / **苹果爱丽丝·红带**
//    —— 拼色是主题的可选属性，纯颜色、不是结构（见 styleOf）。
//    📌 **"有色带"与"声明撞色"是两件独立的事**（V151 踩明白的）：
//       粉帽 / 青提是"常规 + 色带"；苹果爱丽丝是"**撞色 + 色带**"。
//       ⚠️ 它还是**第一套"深色带"**（带是深红）⇒ 逼出 `bandInk` / `bandInkOn` 两个可选变量：
//          带内那几处元素是按"浅带"配的（带上深字、实心块用主色），压在深带上会看不见。
//       判断走哪条分支，
//       看的是"**底与主色的色相差**"，不是"名字里有没有撞色"、更不是"有没有色带"。
//
// 三条铁律（见文档仓《19-主题配色方案.md》第四节）：
//   铁律 1  换气质不换信息 —— 成功/警告/危险/信息四色**永不随主题变**（它们不在本文件里）
//   铁律 2  一套主题 = 13 个 token 全给，键集合必须完全一致
//   铁律 3  常驻元素必须一起换（tabBar / 导航栏 / 硬编码色，在页面层处理）
//
// ⚠️ 三个容易踩的点：
//   ① **主色一律是用户色板里的原色，不许压深**（D129/D130 定案）。
//      "浅色主色配白字看不清"这件事，靠 `primary-on` 自动择字色解决 ——
//      改的是"字色"，不是"用户给的色"。
//   ② 变量名必须与 app.wxss 里的口径**逐字一致**（`--color-primary-soft` 等）；
//      名字写错在微信里是**静默失效**（不报错、只是颜色不对）。
//   ③ **软底 / 中性底必须与主色同色调**（2026-10-03 V98 定案，被真机逼出来的）：
//      色板那格「浅色」只有在它与主色同色调（≤30°）时才拿来当软底；
//      不同色调就**按主色推导**（保色相=主色，保原来的饱和度/明度）。
//      为什么：某套的色板是「奶黄 + 粉」，直接拿粉当软底 ⇒ 界面一片粉，
//      而粉正是**另一套**的色调 —— 用户的原话是
//      「换成姜饼小熊仁怎么还混着别的主题 你能不能行 换主题就要整个都换啊」。
//      注意分组：软底/各种底跟**主色**同色调；次级文字（text-2/3）跟**正文色**同色调
//      （正文色来自色板「深色」，本身就可能不是主色一路）。
//      判据在 tests/themes.test.js ⑨，越界就红。
//   ④ **卡片必须"看得出来是主题色"**（2026-10-03 V99 用户："为什么这些卡片都是白色的
//      不能用主题的颜色吗"）：`bg / surface / surface-2 / divider` 这四个"地面色"一律
//      按**主色混白**的固定阶梯推导 —— 底 5% / 卡面 13% / 内底 25% / 分隔线 33%。
//      为什么不能只调卡面：卡面和白底差得太少时，卡片就"糊"在页面里；阶梯一起走才有层次。
//      判据在 tests/themes.test.js ⑩（卡面与纯白的距离不许太小）。
//   ⑤ **"撞色"型主题必须显式声明 `contrast: true`**（2026-10-03 定）：
//      这套是**冷底 + 暖主色** —— 粉蓝 `#BCD7DE` 铺地面、黑可可 `#583722` 当主色与文字，
//      两组**刻意**分居冷暖两端。这跟 V98 那次「拿别的主题的色当软底」**不是一回事**：
//      那次是"意外把别的主题的色混进来了"，这次是"照着设计稿有意撞色"。
//      机器分不出这两者 ⇒ 由主题**自己声明**：声明了的走判据 ⑨ 的撞色分支
//      （不再要求色相同色调，改查"主色在两种底上还读不读得出来"）；**没声明的一律按原判**。
//      ⚠️ 这条口子不许随手开 —— 它只给"有设计稿依据"的撞色用。

